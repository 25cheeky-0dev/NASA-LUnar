"""Export authoritative OpenAPI and TypeScript directly from runtime response schemas."""

import argparse
import json
from pathlib import Path

from app.main import app

ROOT = Path(__file__).resolve().parents[2]
OPENAPI = ROOT / "docs/contracts/science.openapi.json"
TYPES = ROOT / "docs/contracts/science.generated.ts"


def ts_type(schema):
    if "$ref" in schema:
        return schema["$ref"].rsplit("/", 1)[-1]
    if "const" in schema:
        return json.dumps(schema["const"])
    if "enum" in schema:
        return " | ".join(json.dumps(x) for x in schema["enum"])
    for key, joiner in [("anyOf", " | "), ("oneOf", " | "), ("allOf", " & ")]:
        if key in schema:
            return "(" + joiner.join(ts_type(s) for s in schema[key]) + ")"
    kind = schema.get("type")
    if kind == "null":
        return "null"
    if kind in ("integer", "number"):
        return "number"
    if kind == "boolean":
        return "boolean"
    if kind == "string":
        return "string"
    if kind == "array":
        if "prefixItems" in schema:
            return "[" + ", ".join(ts_type(s) for s in schema["prefixItems"]) + "]"
        return "Array<" + ts_type(schema.get("items", {})) + ">"
    if kind == "object" or "properties" in schema:
        required = schema.get("required", [])
        fields = [
            json.dumps(k) + ("" if k in required else "?") + ": " + ts_type(v) + ";"
            for k, v in schema.get("properties", {}).items()
        ]
        extra = schema.get("additionalProperties", True)
        if extra is not False:
            fields.append(
                "[key: string]: " + (ts_type(extra) if isinstance(extra, dict) else "unknown") + ";"
            )
        return "{ " + " ".join(fields) + " }"
    if not schema or set(schema).issubset({"title", "description", "default"}):
        return "unknown"
    raise ValueError(f"Unsupported JSON schema: {schema}")


def artifacts():
    schema = app.openapi()
    text = json.dumps(schema, indent=2, sort_keys=True) + "\n"
    lines = [
        "// Generated by python -m scripts.export_science_contract. Do not edit.",
        "// JSON Schema/OpenAPI constraints remain authoritative; TS cannot express numerical limits.",
    ]
    for name, definition in sorted(schema["components"]["schemas"].items()):
        lines.append(f"export type {name} = {ts_type(definition)};")
    lines.append("export type ScienceOperations = {")
    for path, operations in schema["paths"].items():
        if not path.startswith("/api/v1/science/"):
            continue
        for method, operation in operations.items():
            if method not in ("get", "post"):
                continue
            content = operation["responses"]["200"].get("content", {})
            if "application/json" not in content:
                continue  # Binary visualization response; no JSON TypeScript model.
            response = content["application/json"]["schema"]
            request = (
                operation.get("requestBody", {})
                .get("content", {})
                .get("application/json", {})
                .get("schema")
            )
            parameters = {}
            for param in operation.get("parameters", []):
                parameters[param["name"] + ("" if param.get("required") else "?")] = ts_type(
                    param["schema"]
                )
            params = "{ " + " ".join(k + ": " + v + ";" for k, v in parameters.items()) + " }"
            lines.append(
                json.dumps(method.upper() + " " + path)
                + ": { parameters: "
                + params
                + "; body: "
                + (ts_type(request) if request else "never")
                + "; response: "
                + ts_type(response)
                + "; error: ScienceError; };"
            )
    lines.append("};")
    return text, "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    for path, content in zip((OPENAPI, TYPES), artifacts(), strict=True):
        if args.check:
            if path.read_text(encoding="utf-8") != content:
                raise SystemExit(f"Stale generated contract: {path.name}")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8")


if __name__ == "__main__":
    main()
